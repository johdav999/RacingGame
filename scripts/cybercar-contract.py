"""Regenerate the game-specific contract from the prepared clean cybercar."""
import hashlib
import json
import struct
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = (root / "assets/runtime/models/cybercar-clean-detail/cybercar.glb").read_bytes()
doc = json.loads(data[20:20 + struct.unpack_from("<I", data, 12)[0]])
wheels = ["wheel_front_left", "wheel_front_right", "wheel_rear_left", "wheel_rear_right"]
rows = []

def number(value):
    return f"{float(value):.10e}f"

def visit(index):
    node = doc["nodes"][index]
    assert "matrix" not in node and "rotation" not in node and "scale" not in node
    if "mesh" in node:
        primitives = doc["meshes"][node["mesh"]]["primitives"]
        assert len(primitives) == 1 and primitives[0].get("mode", 4) == 4
        count = doc["accessors"][primitives[0]["indices"]]["count"]
        pivot = node.get("translation", [0, 0, 0])
        wheel = wheels.index(node["name"]) if node["name"] in wheels else -1
        radius = node.get("extras", {}).get("radius_source_units", 0)
        rows.append('    {"%s", %d, %d, {%s}, %s},' % (
            node["name"], count, wheel, ",".join(map(number, pivot)), number(radius)))
    else:
        assert "translation" not in node
    for child in node.get("children", []):
        visit(child)

for index in doc["scenes"][doc.get("scene", 0)]["nodes"]:
    visit(index)
assert all(any(('"'+name+'"') in row for row in rows) for name in wheels)
header = """// Generated by scripts/cybercar-contract.py from cybercar-clean-detail/cybercar.glb.
#pragma once
#include "engine/math.hpp"
#include <array>
namespace racing::cybercar {
inline constexpr char sha256[] = "%s";
inline constexpr unsigned triangles=%d;
struct Part { const char* name; unsigned indices; int wheel; engine::Vec3 pivot; float radius; };
inline constexpr std::array<Part,%d> parts{{
%s
}};
inline constexpr float scale=4.3f, bodyOffsetY=-.65f, restSuspension=.30f;
inline constexpr float suspensionMin=.24f, suspensionMax=.38f;
// Source -X forward / +Y up becomes game +Z forward / +Y up.
inline engine::Vec3 direction(engine::Vec3 v) { return {v.z,v.y,-v.x}; }
inline engine::Vec3 point(engine::Vec3 v) { return direction(v)*scale+engine::Vec3{0,bodyOffsetY,0}; }
}
""" % (hashlib.sha256(data).hexdigest(),sum(doc['accessors'][p['indices']]['count']//3 for mesh in doc['meshes'] for p in mesh['primitives']),len(rows), "\n".join(rows))
(root / "src/cybercar_contract.hpp").write_text(header)
print(f"Generated {len(rows)}-part contract:", hashlib.sha256(data).hexdigest())
